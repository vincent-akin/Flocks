/**
 * Seeds three real, deployable demo churches - each its own Church
 * Organization (tenant) - with the parishes, a Parish Admin (pastor) per
 * parish, and 50-110 members per parish, every one of them with a real
 * login. This is meant to be the actual starting dataset for a freshly
 * deployed instance, not a throwaway fixture: it writes through the same
 * `connectDB()` used by the server itself (src/config/db.js is untouched),
 * and everyone it creates can log in and use the app for real. Replace
 * this data gradually with real churches as they onboard.
 *
 * The actual dataset (who exists, their names, emails, passwords, and
 * statuses) is entirely generated by scripts/lib/demo-church-dataset.js,
 * which has no database dependency at all and is fully deterministic.
 * This file's only job is to take that dataset and write it into
 * MongoDB. That split means `node scripts/generate-demo-credentials.js`
 * (no database needed) always describes exactly what this script (with a
 * database) will actually create - see that file to preview or re-print
 * credentials without touching the database at all.
 *
 * Usage:
 *   npm run seed:demo-churches
 *
 * Safe to re-run: it deletes any previous run of these three specific
 * demo organizations (by slug) and every record beneath them, then
 * recreates everything from scratch.
 *
 * Deliberately avoids MongoDB multi-document transactions (unlike the
 * API's own controllers) so it works against a plain standalone MongoDB
 * instance too, not just a replica set - see server/README.md for why
 * the API itself requires a replica set; this script does not.
 */

require('dotenv').config();
const fs = require('fs');
const path = require('path');
const mongoose = require('mongoose');

const connectDB = require('../src/config/db');
const { buildDataset, renderCredentialsMarkdown } = require('./lib/demo-church-dataset');

const ChurchOrganization = require('../src/models/ChurchOrganization');
const Parish = require('../src/models/Parish');
const Member = require('../src/models/Member');
const User = require('../src/models/User');
const ParishMembership = require('../src/models/ParishMembership');
const RoleAssignment = require('../src/models/RoleAssignment');
const MemberEvent = require('../src/models/MemberEvent');

const { ROLES, SCOPE_TYPES, ALL_PERMISSIONS, DEFAULT_PARISH_ADMIN_PERMISSIONS } = require('../src/permissions/permissions');

const HASH_CONCURRENCY = 20; // bcrypt is CPU-bound; a small pool keeps memory sane without serializing everything

/** Runs `fn` over `items` with at most `limit` in flight at once. */
async function mapWithConcurrency(items, limit, fn) {
  const results = new Array(items.length);
  let cursor = 0;

  async function worker() {
    while (cursor < items.length) {
      const current = cursor;
      cursor += 1;
      results[current] = await fn(items[current], current);
    }
  }

  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, worker));
  return results;
}

// ---------------------------------------------------------------------
// Cleanup - remove any previous run of exactly these demo organizations
// ---------------------------------------------------------------------

async function deleteExistingDemoChurches(dataset) {
  const slugs = dataset.map((c) => c.slug);
  const existing = await ChurchOrganization.find({ slug: { $in: slugs } }).select('_id slug').lean();
  if (!existing.length) return;

  const organizationIds = existing.map((org) => org._id);

  await Promise.all([
    RoleAssignment.deleteMany({ organization: { $in: organizationIds } }),
    ParishMembership.deleteMany({ organization: { $in: organizationIds } }),
    MemberEvent.deleteMany({ organization: { $in: organizationIds } }),
    User.deleteMany({ organization: { $in: organizationIds } }),
    Member.deleteMany({ organization: { $in: organizationIds } }),
    Parish.deleteMany({ organization: { $in: organizationIds } }),
  ]);
  await ChurchOrganization.deleteMany({ _id: { $in: organizationIds } });

  console.log(`[seed] Removed ${existing.length} previous demo organization(s): ${existing.map((o) => o.slug).join(', ')}`);
}

// ---------------------------------------------------------------------
// Persisting one resolved person (super admin or pastor) with a role
// ---------------------------------------------------------------------

async function persistLeader({ organization, parish, person, role, scopeType, scopeId, permissions }) {
  const member = await Member.create({
    organization: organization._id,
    primaryParish: parish._id,
    firstName: person.firstName,
    lastName: person.lastName,
    email: person.email,
    membershipStatus: 'ACTIVE',
    baptismStatus: 'BAPTIZED',
    discipleshipStatus: 'COMPLETED',
  });

  const user = await User.create({
    organization: organization._id,
    email: person.email,
    passwordHash: await User.hashPassword(person.password),
    isEmailVerified: true,
    member: member._id,
  });

  member.user = user._id;
  await member.save();

  await ParishMembership.create({ organization: organization._id, member: member._id, parish: parish._id, isCurrent: true });

  await RoleAssignment.create({ user: user._id, organization: organization._id, role, scopeType, scopeId, permissions });

  await MemberEvent.create({
    organization: organization._id,
    member: member._id,
    parish: parish._id,
    type: 'JOINED_CHURCH',
    title: 'Joined Church',
  });
}

// ---------------------------------------------------------------------
// Persisting a parish's regular members in bulk
// ---------------------------------------------------------------------

async function persistParishMembers({ organization, parish, members }) {
  const memberDocs = await Member.insertMany(
    members.map((m) => ({
      organization: organization._id,
      primaryParish: parish._id,
      firstName: m.firstName,
      lastName: m.lastName,
      email: m.email,
      gender: m.gender,
      membershipStatus: m.membershipStatus,
      baptismStatus: m.baptismStatus,
      discipleshipStatus: m.discipleshipStatus,
    }))
  );

  // bcrypt hashing is the slow part - bound the concurrency.
  const passwordHashes = await mapWithConcurrency(members, HASH_CONCURRENCY, (m) => User.hashPassword(m.password));

  const userDocs = await User.insertMany(
    memberDocs.map((member, i) => ({
      organization: organization._id,
      email: members[i].email,
      passwordHash: passwordHashes[i],
      isEmailVerified: true,
      member: member._id,
    }))
  );

  // Link each Member back to its User (insertMany can't do this in one pass).
  await Member.bulkWrite(
    memberDocs.map((member, i) => ({
      updateOne: { filter: { _id: member._id }, update: { $set: { user: userDocs[i]._id } } },
    }))
  );

  await ParishMembership.insertMany(
    memberDocs.map((member) => ({ organization: organization._id, member: member._id, parish: parish._id, isCurrent: true }))
  );

  await MemberEvent.insertMany(
    memberDocs.map((member) => ({
      organization: organization._id,
      member: member._id,
      parish: parish._id,
      type: 'JOINED_CHURCH',
      title: 'Joined Church',
    }))
  );

  // No RoleAssignment for plain members - by design, Flocks members are
  // authorized via "is this their own record?" checks, not a granted
  // permission set (see API_DOCUMENTATION.md, Permission Reference).

  return memberDocs.length;
}

// ---------------------------------------------------------------------
// Persisting one whole church from its resolved dataset entry
// ---------------------------------------------------------------------

async function persistChurch(churchData) {
  const organization = await ChurchOrganization.create({
    name: churchData.name,
    slug: churchData.slug,
    contactEmail: `admin@${churchData.slug}.demo.flocks.app`,
    timezone: 'Africa/Lagos',
  });

  console.log(`\n[seed] Created church: ${churchData.name}`);

  const parishDocs = [];
  for (const parishData of churchData.parishes) {
    // eslint-disable-next-line no-await-in-loop
    const parish = await Parish.create({
      organization: organization._id,
      name: parishData.name,
      city: parishData.city,
      country: 'Nigeria',
      isMainParish: parishData.isMainParish,
    });
    parishDocs.push({ data: parishData, doc: parish });
  }

  const mainParish = parishDocs.find((p) => p.data.isMainParish) || parishDocs[0];
  organization.settings.defaultParish = mainParish.doc._id;
  await organization.save();

  await persistLeader({
    organization,
    parish: mainParish.doc,
    person: churchData.superAdmin,
    role: ROLES.SUPER_ADMIN,
    scopeType: SCOPE_TYPES.ORGANIZATION,
    scopeId: organization._id,
    permissions: ALL_PERMISSIONS,
  });

  let totalMembers = 0;
  for (const { data: parishData, doc: parish } of parishDocs) {
    // eslint-disable-next-line no-await-in-loop
    await persistLeader({
      organization,
      parish,
      person: parishData.pastor,
      role: ROLES.ADMIN,
      scopeType: SCOPE_TYPES.PARISH,
      scopeId: parish._id,
      permissions: DEFAULT_PARISH_ADMIN_PERMISSIONS,
    });

    // eslint-disable-next-line no-await-in-loop
    const created = await persistParishMembers({ organization, parish, members: parishData.members });
    totalMembers += created;
    console.log(`[seed]   ${parish.name}: 1 pastor + ${created} members`);
  }

  return { organizationName: organization.name, parishCount: parishDocs.length, memberCount: totalMembers };
}

// ---------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------

async function main() {
  const dataset = buildDataset();

  await connectDB();
  await deleteExistingDemoChurches(dataset);

  const summaries = [];
  for (const churchData of dataset) {
    // eslint-disable-next-line no-await-in-loop
    summaries.push(await persistChurch(churchData));
  }

  const outputDir = path.join(__dirname, 'output');
  fs.mkdirSync(outputDir, { recursive: true });
  const outputPath = path.join(outputDir, 'DEMO_CHURCH_CREDENTIALS.md');
  fs.writeFileSync(outputPath, renderCredentialsMarkdown(dataset));

  const totalLogins = dataset.reduce(
    (sum, c) => sum + 1 + c.parishes.reduce((s, p) => s + 1 + p.members.length, 0),
    0
  );

  console.log('\n[seed] Done.');
  console.log(`[seed] Churches: ${summaries.length}`);
  console.log(`[seed] Parishes: ${summaries.reduce((sum, s) => sum + s.parishCount, 0)}`);
  console.log(`[seed] Members (excl. leaders): ${summaries.reduce((sum, s) => sum + s.memberCount, 0)}`);
  console.log(`[seed] Total login accounts: ${totalLogins}`);
  console.log(`[seed] Credentials written to: ${outputPath}`);

  await mongoose.disconnect();
}

main().catch(async (err) => {
  console.error('[seed] Failed:', err);
  await mongoose.disconnect().catch(() => undefined);
  process.exitCode = 1;
});
